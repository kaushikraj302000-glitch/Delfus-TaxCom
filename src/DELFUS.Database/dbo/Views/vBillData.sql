


CREATE VIEW [dbo].[vBillData]
AS

SELECT 
Id,
LienDataId,
BatchId,
LTRIM(RTRIM(RD_BILL_OUT)) as RD_BILL_OUT,
LTRIM(RTRIM(RD_CNTRCT_ID_OB)) as RD_CNTRCT_ID_OB,
LTRIM(RTRIM(RD_TINET_SEQ_NBR_OB)) as RD_TINET_SEQ_NBR_OB,
LTRIM(RTRIM(RD_TAX_BILL_YR)) as RD_TAX_BILL_YR,
LTRIM(RTRIM(RD_BILL_TYP_DESC)) as RD_BILL_TYP_DESC,
LTRIM(RTRIM(RD_BILL_SEARCH_DT)) as RD_BILL_SEARCH_DT,
LTRIM(RTRIM(RD_BILL_SEARCH_DT_TXT)) as RD_BILL_SEARCH_DT_TXT,
LTRIM(RTRIM(RD_INSTL_NBR)) as RD_INSTL_NBR,
LTRIM(RTRIM(RD_TAX_AMT)) as RD_TAX_AMT,
LTRIM(RTRIM(RD_PRFL_ID_OB)) as RD_PRFL_ID_OB,
LTRIM(RTRIM(RD_SUBAPPL_CD_OB)) as RD_SUBAPPL_CD_OB,
LTRIM(RTRIM(RD_SYI_CD)) as RD_SYI_CD,
LTRIM(RTRIM(RD_SYI_CD_DESC)) as RD_SYI_CD_DESC,
LTRIM(RTRIM(RD_TA_TAX_BILL_YR)) as RD_TA_TAX_BILL_YR,
LTRIM(RTRIM(RD_TAX_1_AMT)) as RD_TAX_1_AMT,
LTRIM(RTRIM(RD_TAX_2_AMT)) as RD_TAX_2_AMT,
LTRIM(RTRIM(RD_TAX_3_AMT)) as RD_TAX_3_AMT,
LTRIM(RTRIM(RD_TAX_4_AMT)) as RD_TAX_4_AMT,
LTRIM(RTRIM(FILLER)) as FILLER
FROM dbo.BillData